// Функция для получения релевантного контекста на основе ключевых слов
export function getRelevantKnowledge(userMessage) {
  const message = userMessage.toLowerCase();
  const context = [];

  // Детектируем тему на основе ключевых слов
  const keywords = {
    anxiety: ['тревог', 'волнен', 'беспоко', 'страх', 'паник', 'anxiety', 'worry', 'сердце', 'дыш'],
    depression: ['грустн', 'подавлен', 'депресс', 'устал', 'апати', 'нет сил', 'depression', 'не могу заставить', 'не хочется', 'нет энергии', 'разбита', 'пусто'],
    anger: ['злость', 'гнев', 'раздраж', 'бесит', 'anger', 'frustrated', 'злюсь'],
    stress: ['стресс', 'напряж', 'перегруз', 'deadline', 'устал', 'переживаю'],
    sleep: ['сон', 'бессонн', 'не могу уснуть', 'sleep', 'insomnia', 'спать'],
    breathing: ['дыхан', 'breathe', 'не могу дышать'],
    mindfulness: ['медитац', 'осознанн', 'mindfulness', 'присутствие'],
    grounding: ['паник', 'тревож', 'заземл', 'grounding', 'panic', 'диссоциац'],
  };

  // Проверяем на признаки необходимости профессиональной помощи
  const crisisKeywords = ['суицид', 'покончить', 'не хочу жить', 'самоубийство', 'suicide'];
  const hasCrisisSignal = crisisKeywords.some(kw => message.includes(kw));
  
  if (hasCrisisSignal) {
    context.push(psychologyKnowledge.referralSigns);
  }

  // Добавляем релевантные техники
  if (keywords.anxiety.some(kw => message.includes(kw))) {
    context.push(psychologyKnowledge.emotionRegulation.anxiety);
    context.push(psychologyKnowledge.techniques.breathing);
    context.push(psychologyKnowledge.techniques.grounding);
  }

  if (keywords.depression.some(kw => message.includes(kw))) {
    context.push(psychologyKnowledge.emotionRegulation.depression);
    context.push(psychologyKnowledge.wellness);
  }

  if (keywords.anger.some(kw => message.includes(kw))) {
    context.push(psychologyKnowledge.emotionRegulation.anger);
  }

  if (keywords.stress.some(kw => message.includes(kw))) {
    context.push(psychologyKnowledge.emotionRegulation.stress);
    context.push(psychologyKnowledge.techniques.breathing);
  }

  if (keywords.grounding.some(kw => message.includes(kw))) {
    context.push(psychologyKnowledge.techniques.grounding);
  }

  // Всегда добавляем базовые принципы поддержки
  context.push(psychologyKnowledge.supportPrinciples);

  // Если не нашли специфичных тем, добавляем общие подходы
  if (context.length === 1) { // только supportPrinciples
    context.push(psychologyKnowledge.approaches.mindfulness);
    context.push(psychologyKnowledge.wellness);
  }

  return context.join('\n\n---\n\n');
}

// Экспорт для использования в API
export default psychologyKnowledge;
